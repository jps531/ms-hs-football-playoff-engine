-- Apply to an existing database (init.sql only runs when the database is first
-- created). Safe to run more than once.
--
--   docker compose exec -T db psql -U postgres -d mshsfootball < sql/migrations/2026_10_game_id.sql
--
-- ---------------------------------------------------------------------------
-- games.game_id: one id for a game, shared by both schools' rows
-- ---------------------------------------------------------------------------
-- A game's date can change (AHSFHS reschedules it, or the two schools' pages
-- date it a day apart), so (school, date) is a poor way to refer to one.
-- game_id stays put. Adding the column gives every existing row its own id;
-- the UPDATE then gives each game's two rows the same one: rows that are each
-- other's nearest match (the opponent's row against this school, same season,
-- within 3 days, the later date on a tie), taking the smaller of their ids.
-- That's the rule backend/helpers/game_ids.py applies on every AHSFHS run.
--
-- games_effective.game_date then reads the game's rows by game_id, and the
-- view gains a game_id column (last, so CREATE OR REPLACE adds it in place).

ALTER TABLE games ADD COLUMN IF NOT EXISTS game_id BIGINT GENERATED BY DEFAULT AS IDENTITY;

WITH cand AS (
  SELECT g.school, g.date, g.game_id, o.school AS o_school, o.date AS o_date, o.game_id AS o_id,
         row_number() OVER (PARTITION BY g.school, g.date ORDER BY abs(o.date - g.date), o.date DESC) AS rn
  FROM games g
  JOIN games o ON o.season = g.season AND o.school = g.opponent AND o.opponent = g.school
              AND o.date BETWEEN g.date - 3 AND g.date + 3
),
best AS (SELECT * FROM cand WHERE rn = 1),
pairs AS (
  SELECT a.school, a.date, LEAST(a.game_id, a.o_id) AS game_id
  FROM best a
  JOIN best b ON b.school = a.o_school AND b.date = a.o_date AND b.o_school = a.school AND b.o_date = a.date
)
UPDATE games g SET game_id = p.game_id
FROM pairs p
WHERE g.school = p.school AND g.date = p.date AND g.game_id <> p.game_id;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'games_game_id_school_key') THEN
    ALTER TABLE games
      ADD CONSTRAINT games_game_id_school_key UNIQUE (game_id, school) DEFERRABLE INITIALLY DEFERRED;
  END IF;
END $$;

ALTER TABLE games ALTER COLUMN game_id SET NOT NULL;

-- Same as sql/init.sql (game_date_sql_test keeps them identical).
CREATE OR REPLACE VIEW games_effective AS
SELECT
  school, date, season, opponent,
  COALESCE(overrides->>'result',      result)      AS result,
  final,
  COALESCE((overrides->>'overtime')::int,         overtime)       AS overtime,
  COALESCE(overrides->>'game_status', game_status) AS game_status,
  COALESCE((overrides->>'game_quarter')::smallint, game_quarter)  AS game_quarter,
  COALESCE(overrides->>'game_clock',               game_clock)    AS game_clock,
  source,
  helmet_design_id,
  COALESCE(overrides->>'location',                location)       AS location,
  COALESCE((overrides->>'location_id')::int,      location_id)    AS location_id,
  COALESCE((overrides->>'points_for')::int,       points_for)     AS points_for,
  COALESCE((overrides->>'points_against')::int,   points_against) AS points_against,
  COALESCE(
    (overrides->>'region_game')::boolean,
    COALESCE(overrides->>'round', round) IS NULL AND EXISTS (
      SELECT 1
      FROM school_seasons a
      JOIN school_seasons b
        ON b.season = a.season AND b.class = a.class AND b.region = a.region
      WHERE a.school = games.school AND a.season = games.season AND b.school = games.opponent
    )
  ) AS region_game,
  COALESCE(overrides->>'round',                   round)          AS round,
  COALESCE((overrides->>'kickoff_time')::timestamptz, kickoff_time) AS kickoff_time,
  overrides,
  pregame_prob, pregame_prob_computed_at,
  COALESCE((overrides->>'ot_period_start_score_for')::int,     ot_period_start_score_for)     AS ot_period_start_score_for,
  COALESCE((overrides->>'ot_period_start_score_against')::int, ot_period_start_score_against) AS ot_period_start_score_against,
  COALESCE(overrides->>'ot_next_possession',      ot_next_possession) AS ot_next_possession,
  -- The game's own date, the same in both schools' rows. The two rows of one
  -- game can carry dates a day apart (each school's page is scraped on its
  -- own), and anything cut off at a date must put both rows on the same side
  -- of it. The later of the two dates wins.
  (SELECT MAX(o.date) FROM games o WHERE o.game_id = games.game_id) AS game_date,
  game_id
FROM games;
